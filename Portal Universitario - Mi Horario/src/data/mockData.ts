// Helper to build N1..N6 nightly block schedules
type BlockAssignment = Record<
  string,
  {
    status?: ClassroomStatus;
    subjectName?: string;
    subjectCode?: string;
    group?: string;
    professor?: string;
    note?: string;
    isOpenService?: boolean;
  }
>;

function buildNightSchedule(
  assignments: BlockAssignment = {},
  defaultStatus: ClassroomStatus = 'Libre',
  officeOpenBlocks?: string[],
  serviceScheduleLabel?: string
): Record<string, ClassroomHourSession> {
  const result: Record<string, ClassroomHourSession> = {};
  NIGHT_BLOCKS.forEach((blk) => {
    const custom = assignments[blk.code];
    if (custom) {
      result[blk.code] = {
        blockCode: blk.code,
        status: custom.status || 'Ocupado',
        subjectName: custom.subjectName,
        subjectCode: custom.subjectCode,
        group: custom.group,
        professor: custom.professor,
        note: custom.note,
        isOpenService: custom.isOpenService,
      };
    } else if (defaultStatus === 'Administrativo') {
      const isOpen = officeOpenBlocks ? officeOpenBlocks.includes(blk.code) : true;
      result[blk.code] = {
        blockCode: blk.code,
        status: 'Administrativo',
        isOpenService: isOpen,
        subjectName: officeOpenBlocks
          ? isOpen
            ? `Abierto · ${serviceScheduleLabel || 'Turno nocturno'}`
            : `Cerrado · Horario: ${serviceScheduleLabel || 'Concluido'}`
          : 'Área de servicio universitario',
        note: officeOpenBlocks
          ? isOpen
            ? `Atención activa (${serviceScheduleLabel})`
            : `Fuera de horario de atención (${serviceScheduleLabel})`
          : 'Espacio no disponible para clases regulares',
      };
    } else {
      result[blk.code] = {
        blockCode: blk.code,
        status: defaultStatus,
      };
    }
  });
  return result;
}

function makeSensor(
  code: string,
  schedule: Record<string, ClassroomHourSession>,
  overridePeople?: number
): SensorTelemetry {
  const n1Status = schedule['N1']?.status || 'Libre';
  const people =
    overridePeople !== undefined
      ? overridePeople
      : n1Status === 'Ocupado'
      ? 24
      : n1Status === 'Reservado'
      ? 14
      : 0;
  return {
    sensorId: `IOT-${code}`,
    online: true,
    motionDetected: people > 0,
    estimatedPeople: people,
    temperatureC: people > 10 ? 23 : 21,
    lastUpdated: 'Hace 1 min (Simulado)',
  };
}

function createRoom(params: {
  code: string;
  name: string;
  buildingCode: '800' | '700' | '900';
  floor: number;
  wing: 'Izquierda' | 'Derecha' | 'Centro';
  type: SpaceType;
  capacity: number;
  equipment: string[];
  accessNote: string;
  lastVerifiedBy?: string;
  lastVerifiedAt?: string;
  prefecturaObservation?: string;
  assignments?: BlockAssignment;
  defaultStatus?: ClassroomStatus;
  officeOpenBlocks?: string[];
  serviceScheduleLabel?: string;
  isMeetingPoint?: boolean;
  overrideSensorPeople?: number;
}): Classroom {
  const buildingNames: Record<'800' | '700' | '900', string> = {
    '800': 'Edificio 800',
    '700': 'Edificio 700',
    '900': 'Edificio 900',
  };
  const floorLabel =
    params.floor === 1
      ? 'Piso 1 (Planta Baja)'
      : (params.buildingCode === '800' || params.buildingCode === '700') && params.floor === 6
      ? 'Piso 6 (Azotea)'
      : `Piso ${params.floor}`;

  const hourlySchedule = buildNightSchedule(
    params.assignments,
    params.defaultStatus || 'Libre',
    params.officeOpenBlocks,
    params.serviceScheduleLabel
  );

  return {
    id: `room-${params.buildingCode}-${params.code.toLowerCase()}`,
    code: params.code,
    name: params.name,
    building: buildingNames[params.buildingCode],
    buildingCode: params.buildingCode,
    floor: params.floor,
    floorLabel,
    wing: params.wing,
    type: params.type,
    capacity: params.capacity,
    equipment: params.equipment,
    accessNote: params.accessNote,
    lastVerifiedBy: params.lastVerifiedBy || 'Prefectura UNEZ',
    lastVerifiedAt: params.lastVerifiedAt || 'Hace 6 min',
    prefecturaObservation: params.prefecturaObservation,
    serviceScheduleLabel: params.serviceScheduleLabel,
    isMeetingPoint: params.isMeetingPoint,
    hourlySchedule,
    sensor: makeSensor(params.code, hourlySchedule, params.overrideSensorPeople),
  };
}

